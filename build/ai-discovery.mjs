#!/usr/bin/env node
/* =========================================================================
   ai-discovery.mjs - the arcade's AI discovery file stack

   Writes the ten AI Discovery Files (ADF-001 to ADF-010, spec v2.2.2,
   ai-visibility.org.uk) into the arcade folder from games.json and
   build/ai-data.json, so they are served at menj.buzz/arcade/<file>.
   Same layout as menj.buzz/build/ai-discovery.mjs. No dependencies.

   Run from anywhere:  node build/ai-discovery.mjs
   ========================================================================= */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const at = (f) => resolve(root, f);
const data = JSON.parse(readFileSync(at('build/ai-data.json'), 'utf8'));
// The hub lets a game's own game.json override its title and tagline, so do the same here.
const own = (g) => {
  try { return JSON.parse(readFileSync(at(`${g.path}game.json`), 'utf8')); } catch { return {}; }
};
const games = (JSON.parse(readFileSync(at('games.json'), 'utf8')).games || [])
  .filter((g) => g.status === 'live')
  .map((g) => { const o = own(g); return { ...g, title: o.title || g.title, tagline: o.tagline || g.tagline }; });

const BASE = data.base.replace(/\/$/, '');
const lang = data.lang;
const name = data.name;
const today = new Date().toISOString().slice(0, 10);

const SPEC_URL = 'https://www.ai-visibility.org.uk/specifications/';
const SPEC = {
  'llms.txt': ['llms-txt', 'ADF-001', 'AI-readable identity'],
  'llm.txt': ['llm-txt', 'ADF-002', 'Compatibility alias for llms.txt'],
  'llms.html': ['llms-html', 'ADF-003', 'Human-readable reference version'],
  'ai.txt': ['ai-txt', 'ADF-004', 'AI usage permissions'],
  'ai.json': ['ai-json', 'ADF-005', 'Machine-parseable permissions'],
  'identity.json': ['identity-json', 'ADF-006', 'Structured identity'],
  'brand.txt': ['brand-txt', 'ADF-007', 'Naming and terminology'],
  'faq-ai.txt': ['faq-ai-txt', 'ADF-008', 'FAQs formatted for AI'],
  'developer-ai.txt': ['developer-ai-txt', 'ADF-009', 'Technical context for developers'],
  'robots-ai.txt': ['robots-ai-txt', 'ADF-010', 'AI crawler-specific directives']
};
const GENERATOR = 'Generated by build/ai-discovery.mjs (AI Discovery Files spec layout, v2.2.2)';
const specLabel = (f) => `${f} Specification (${SPEC[f][1]})`;
const specUrl = (f) => `${SPEC_URL}${SPEC[f][0]}/`;
const specHead = (f) => `# ${specLabel(f)}\n# ${specUrl(f)}\n# ${GENERATOR}\n`;
const specFoot = (f) => `\n---\n${specLabel(f)}\n${specUrl(f)}\n${GENERATOR}\n`;
const specJson = (f) => ({ _specification: specUrl(f), _generator: GENERATOR });
const header = (title, f) => `${specHead(f)}# ${title}\n\nLang: ${lang}\nWebsite: [${BASE}/](${BASE}/)\nLast Updated: ${today}\n\n`;
const list = (a) => a.map((x) => `- ${x}`).join('\n');
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const files = Object.keys(SPEC);

/* ---- permissions shared by ai.txt and ai.json ---- */
const p = data.permissions;
const cond = p.attributionRequired ? [`Attribution to ${name} is required`] : [];
const withCond = (e) => (cond.length ? { ...e, conditions: cond } : e);
const permissionEntries = [
  p.quote && withCond({ action: 'quote', description: 'Quote passages from this website' }),
  p.summarise && withCond({ action: 'summarise', description: 'Summarise publicly available content from this website' }),
  p.index && { action: 'index', description: 'Index the content for retrieval' },
  p.train && withCond({ action: 'train', description: 'Use the content as training data' }),
  p.commercial && withCond({ action: 'commercial', description: 'Use the content in commercial products' })
].filter(Boolean);
const restrictions = p.restrictions;
if (!p.train) restrictions.push({ action: 'train', severity: 'must-not', description: 'Use content from this website for AI model training' });
if (!p.commercial) restrictions.push({ action: 'commercial', severity: 'must-not', description: 'Use content from this website in commercial products' });

/* ---- ADF-001/002 llms.txt, llm.txt ---- */
let llms = `# ${name}\n\nLang: ${lang}\n\n> ${data.tagline}\n\n- Website: [${BASE}/](${BASE}/)\n- Part of: [${data.parent}](${data.parent})\n`;
llms += `\n## Summary\n\n${data.summary}\n`;
llms += `\n## Contact\n\n- [Contact Page](${data.contact.url})\n`;
llms += `\n## Games\n\n${games.map((g) => `- [${g.title}](${BASE}/${g.path}) - ${g.tagline || ''}`.trimEnd()).join('\n')}\n`;
llms += `\n## Usage\n\nAI systems MAY:\n\n${list(permissionEntries.map((e) => e.description))}\n`;
llms += `\nAI systems MUST NOT:\n\n${list(restrictions.filter((r) => r.severity !== 'should-not').map((r) => r.description))}\n`;
llms += `\nFull policy: [${BASE}/ai.txt](${BASE}/ai.txt)\n`;
llms += `\n## AI Discovery Files\n\n${files.filter((f) => f !== 'llms.txt').map((f) => `- [${f}](${BASE}/${f}) - ${SPEC[f][2]}`).join('\n')}\n`;
writeFileSync(at('llms.txt'), llms + specFoot('llms.txt'));
writeFileSync(at('llm.txt'), llms + specFoot('llm.txt'));

/* ---- ADF-003 llms.html ---- */
const md = (t) => esc(t).replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2">$1</a>');
const html = llms.split('\n').map((l) => {
  if (l.startsWith('# ')) return `<h1>${esc(l.slice(2))}</h1>`;
  if (l.startsWith('## ')) return `<h2>${esc(l.slice(3))}</h2>`;
  if (l.startsWith('> ')) return `<blockquote>${esc(l.slice(2))}</blockquote>`;
  if (l.startsWith('- ')) return `<li>${md(l.slice(2))}</li>`;
  return l.trim() ? `<p>${md(l)}</p>` : '';
}).join('\n').replace(/(<li>[\s\S]*?<\/li>)(?!\n<li>)/g, '<ul>\n$1\n</ul>');
const ld = { '@context': 'https://schema.org', '@type': 'WebSite', name, url: `${BASE}/`, description: data.tagline, inLanguage: lang, publisher: { '@type': 'Person', name: data.owner, url: data.parent } };
writeFileSync(at('llms.html'), `<!DOCTYPE html>
<html lang="${lang}">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${esc(name)} - AI Discovery File</title>
<meta name="description" content="${esc(data.tagline)}">
<meta name="robots" content="index, follow">
<link rel="canonical" href="${BASE}/llms.html">
<link rel="stylesheet" href="css/hub.css">
<script type="application/ld+json">${JSON.stringify(ld).replace(/</g, '\\u003c')}</script>
</head>
<body>
<main class="wrap" style="max-width:46rem;padding-block:3rem">
${html}
<p class="muted"><small>${esc(specLabel('llms.html'))} · <a href="${specUrl('llms.html')}">${specUrl('llms.html')}</a></small></p>
</main>
</body>
</html>
`);

/* ---- ADF-004 ai.txt ---- */
const mustNot = restrictions.filter((r) => r.severity !== 'should-not');
const shouldNot = restrictions.filter((r) => r.severity === 'should-not');
let ai = header(`AI Usage Policy for ${name}`, 'ai.txt');
ai += `## Permissions\n\nAI systems MAY:\n\n${list(permissionEntries.map((e) => e.description + (e.conditions ? ` (${e.conditions.map((c) => c[0].toLowerCase() + c.slice(1)).join('; ')})` : '')))}\n\n`;
ai += `## Restrictions\n\n`;
if (mustNot.length) ai += `AI systems MUST NOT:\n\n${list(mustNot.map((r) => r.description))}\n\n`;
if (shouldNot.length) ai += `AI systems SHOULD NOT:\n\n${list(shouldNot.map((r) => r.description))}\n\n`;
ai += `## AI Training\n\n${p.train ? "This website's content may be used for AI model training." : "This website's content must not be used for AI model training."}\n\n`;
if (p.attributionRequired) ai += `## Attribution Requirements\n\nWhen citing this website, reference ${name} and link to [${BASE}/](${BASE}/)\n\n`;
if (p.citationFormat) ai += `## Citation Format\n\nWhen citing content from this website, use:\n\n${p.citationFormat}\n\n`;
ai += `## Crawler Access\n\nAll AI crawlers are permitted to access this website.\nSee robots.txt and robots-ai.txt for specific directives.\n\n`;
ai += `## Contact\n\n[Contact Page](${data.contact.url})\n${data.contact.preferred}\n\n`;
ai += `## Related Files\n\n- [Machine-parseable version (ai.json)](${BASE}/ai.json)\n- [AI crawler directives (robots-ai.txt)](${BASE}/robots-ai.txt)\n- [robots.txt](${new URL('/robots.txt', BASE).href})\n`;
writeFileSync(at('ai.txt'), ai);

/* ---- ADF-005 ai.json ---- */
writeFileSync(at('ai.json'), JSON.stringify({
  $schema: `${SPEC_URL}ai-json/ai-json.schema.json`,
  language: lang, name, url: `${BASE}/`,
  permissions: permissionEntries, restrictions,
  attribution: { required: !!p.attributionRequired, ...(p.citationFormat ? { format: p.citationFormat } : {}) },
  contact: { url: data.contact.url },
  scope: { appliesTo: `All publicly accessible content on ${BASE}/` },
  licensing: { aiTrainingAllowed: !!p.train },
  metadata: { lastUpdated: today, generator: GENERATOR },
  relatedFiles: { humanReadable: `${BASE}/ai.txt`, identity: `${BASE}/identity.json`, brandGuidelines: `${BASE}/brand.txt`, crawlerDirectives: `${BASE}/robots-ai.txt` },
  ...specJson('ai.json')
}, null, 2) + '\n');

/* ---- ADF-006 identity.json ---- */
writeFileSync(at('identity.json'), JSON.stringify({
  $schema: `${SPEC_URL}identity-json/identity-json.schema.json`,
  language: lang, name, alternateName: data.brand.alsoKnownAs, url: `${BASE}/`, type: 'WebSite',
  description: data.tagline,
  contactPoints: [{ type: 'General Enquiries', url: data.contact.url }],
  services: games.map((g) => g.title),
  industry: 'Browser games',
  metadata: { lastUpdated: today },
  relatedFiles: { llms: `${BASE}/llms.txt`, permissions: `${BASE}/ai.json`, brandGuidelines: `${BASE}/brand.txt` },
  ...specJson('identity.json')
}, null, 2) + '\n');

/* ---- ADF-007 brand.txt ---- */
const b = data.brand;
let brand = header(`Brand Guidelines for ${b.officialName}`, 'brand.txt');
brand += `## Official Name\n\n${b.officialName}\n\n`;
if (b.alsoKnownAs.length) brand += `## Also Known As\n\nThe following names are acceptable alternatives:\n\n${list(b.alsoKnownAs)}\n\n`;
if (b.misspellings.length) brand += `## Common Misspellings\n\nThe following are known misspellings. Correct them to the official name above:\n\n${list(b.misspellings)}\n\n`;
if (b.doNotUse.length) brand += `## Do Not Use\n\nThe following names should never be used to refer to this site:\n\n${list(b.doNotUse)}\n\n`;
brand += `## Brand Voice\n\n${b.voice}\n\n## Taglines\n\n${list(b.taglines)}\n\n## About\n\n${data.summary}\n\n`;
brand += `## Related Files\n\n- [Structured identity (identity.json)](${BASE}/identity.json)\n- [Full profile (llms.txt)](${BASE}/llms.txt)\n`;
writeFileSync(at('brand.txt'), brand);

/* ---- ADF-008 faq-ai.txt ---- */
let faq = header(`Frequently Asked Questions - ${name}`, 'faq-ai.txt');
data.faqs.forEach((f) => { faq += `---\n\nQ: ${f.question}\nA: ${f.answer}\n${f.url ? `URL: [More information](${f.url})\n` : ''}\n`; });
faq += `---\n\nLearn more: [llms.txt](${BASE}/llms.txt)\n`;
writeFileSync(at('faq-ai.txt'), faq);

/* ---- ADF-009 developer-ai.txt ---- */
const d = data.developer;
let dev = header(`Technical Context - ${name}`, 'developer-ai.txt');
dev += `## Platform\n\n- ${d.platform}\n- Language: ${lang}\n- Character Set: UTF-8\n\n## Technology Stack\n\n${list(d.stack)}\n\n## Developer Notes\n\n${list(d.notes)}\n\n`;
dev += `## Data Feeds\n\n${list(d.feeds.map((f) => `[${f.label}](${f.url})`))}\n\n`;
dev += `## AI Discovery Files\n\n${list(files.map((f) => `[${f}](${BASE}/${f})`))}\n`;
writeFileSync(at('developer-ai.txt'), dev);

/* ---- ADF-010 robots-ai.txt ---- */
let rai = `${specHead('robots-ai.txt')}# AI Crawler Directives for ${name}\n# Website: ${BASE}/\n# Last Updated: ${today}\n#\n`;
rai += `# This file provides supplementary AI-specific crawler guidance.\n# Standard robots.txt remains the authoritative source for all crawlers.\n\n# Policy: All AI crawlers are permitted.\n\n`;
data.crawlers.allowed.forEach((a) => {
  rai += `User-agent: ${a}\nAllow: /\n${data.crawlers.disallowedPaths.map((x) => `Disallow: ${x}\n`).join('')}\n`;
});
rai += `# Notes for AI systems:\n# - This file supplements robots.txt; it does not replace it.\n`;
rai += `# - See ${BASE}/ai.txt for content usage permissions.\n# - See ${BASE}/ai.json for structured permissions.\n`;
rai += `# - Authoritative crawler rules: ${new URL('/robots.txt', BASE).href}\n`;
writeFileSync(at('robots-ai.txt'), rai);

console.log(`Wrote ${files.length} AI discovery files for ${games.length} live games`);
